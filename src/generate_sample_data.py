"""Generate SIMULATED sample data. None of it is real company data.

Writes to data/sample/:
  simulated_ledger_sheet.csv         - what the Google Sheet (AR ledger) would export
  simulated_qbo_invoices.json        - same shape as a QuickBooks Online API "query Invoice" response
  simulated_qbo_payments.json        - same shape as a QuickBooks Online API "query Payment" response
  simulated_planted_problems.csv     - answer key: the errors we planted on purpose

How it works: first we build one "true" set of invoices and payments. Then we
produce two copies of it, the Sheet and QuickBooks, and break the Sheet copy in
known ways so the reconciliation has something to find.
"""
import csv
import json
import random
from datetime import date, datetime, timedelta

from .common import SAMPLE

SEED = 42                      # fixed seed, so every run gives the same data
AS_OF = date(2026, 10, 31)     # "today" for the sample data (a month-end close)
START, END = date(2026, 6, 1), date(2026, 10, 28)
N_INVOICES = 200
CUSTOMERS = [  # made-up names
    "Alder Ridge Logistics", "Bluebird Dental Group", "Cobalt Freight Co", "Dunmore Hardware",
    "Eastgate Foods", "Fernwood Clinics", "Granite Peak Builders", "Harbor Light Marine",
    "Ironwood Furniture", "Juniper Analytics", "Kestrel Aviation Parts", "Lumen Print Works",
    "Maple and Finch Bakery", "Northbeam Energy", "Oakline Pharmacy", "Pinecrest Schools",
    "Quarry Lane Studios", "Redwater Brewing", "Summit Cycle Shop", "Tidewater Textiles",
]
NOTE = "SIMULATED DATA generated by src/generate_sample_data.py - not real QuickBooks data"


def build_truth(rng):
    terms = {c: rng.choice([15, 30, 30, 45]) for c in CUSTOMERS}          # Net 15/30/45
    lag = {c: rng.choice([-3, 0, 5, 15, 30]) for c in CUSTOMERS}         # how late each customer pays
    dates = sorted(START + timedelta(days=rng.randint(0, (END - START).days)) for _ in range(N_INVOICES))
    truth = []
    for i, inv_date in enumerate(dates):
        cust = rng.choice(CUSTOMERS)
        due = inv_date + timedelta(days=terms[cust])
        total = round(min(max(rng.lognormvariate(8.0, 0.8), 250), 30000), 2)
        pay_date = max(inv_date + timedelta(days=1), due + timedelta(days=lag[cust] + rng.randint(-5, 10)))
        roll = rng.random()
        if roll < 0.06 or pay_date > AS_OF:      # stuck in collections, or not paid yet
            paid = 0.0
        elif roll < 0.14:                        # partial payment
            paid = round(total * rng.uniform(0.3, 0.7), 2)
        else:
            paid = total
        truth.append(dict(id=str(101 + i), number=f"INV-{1001 + i}", customer=cust, inv_date=inv_date,
                          due=due, total=total, paid=paid, pay_date=pay_date if paid else None))
    return truth


def main():
    rng = random.Random(SEED)
    truth = build_truth(rng)
    cust_id = {c: str(i + 1) for i, c in enumerate(CUSTOMERS)}

    # Sheet rows: the person filling the Form marks an invoice Paid only when fully paid.
    sheet = {t["number"]: dict(
        Timestamp=datetime.combine(t["inv_date"], datetime.min.time()) + timedelta(hours=9, minutes=rng.randint(0, 480)),
        Customer=t["customer"], **{"Invoice Number": t["number"]},
        **{"Invoice Date": t["inv_date"].isoformat(), "Due Date": t["due"].isoformat()},
        Amount=t["total"], Status="Paid" if t["paid"] >= t["total"] else "Open", Validation="OK",
    ) for t in truth}
    qb = {t["number"]: t for t in truth}

    # ---- Plant known problems (each invoice gets at most one) ----
    used, planted = set(), []

    def pick(pool, k, problem):
        chosen = rng.sample([t for t in pool if t["number"] not in used], k)
        for t in chosen:
            used.add(t["number"])
            planted.append((t["number"], problem))
        return chosen

    for t in pick(truth, 5, "MISSING_IN_QB"):          # in the Sheet but never entered in QuickBooks
        del qb[t["number"]]
    for t in pick(truth, 5, "MISSING_IN_SHEET"):       # in QuickBooks but nobody filled the Form
        del sheet[t["number"]]
    for t in pick(truth, 6, "AMOUNT_MISMATCH"):        # typo in the Form
        sheet[t["number"]]["Amount"] = round(t["total"] * rng.choice([0.9, 0.95, 1.05, 1.1]), 2)
    fully_paid = [t for t in truth if t["paid"] >= t["total"]]
    unpaid = [t for t in truth if t["paid"] == 0]
    for t in pick(fully_paid, 4, "STATUS_MISMATCH"):   # customer paid, Sheet never updated
        sheet[t["number"]]["Status"] = "Open"
    for t in pick(unpaid, 2, "STATUS_MISMATCH"):       # Sheet says Paid, no payment in QuickBooks
        sheet[t["number"]]["Status"] = "Paid"
    rows = list(sheet.values())
    for t in pick(truth, 3, "DUPLICATE_IN_SHEET"):     # Form submitted twice
        dup = dict(sheet[t["number"]], Validation="ERROR: Duplicate invoice number")
        dup["Timestamp"] += timedelta(days=rng.randint(1, 3))
        rows.append(dup)
    rows.sort(key=lambda r: r["Timestamp"])
    for r in rows:
        r["Timestamp"] = r["Timestamp"].strftime("%Y-%m-%d %H:%M:%S")

    SAMPLE.mkdir(parents=True, exist_ok=True)
    with open(SAMPLE / "simulated_ledger_sheet.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)

    invoices = [{
        "Id": t["id"], "DocNumber": t["number"], "TxnDate": t["inv_date"].isoformat(),
        "DueDate": t["due"].isoformat(), "TotalAmt": t["total"], "Balance": round(t["total"] - t["paid"], 2),
        "CustomerRef": {"value": cust_id[t["customer"]], "name": t["customer"]}, "domain": "QBO",
    } for t in qb.values()]
    payments = [{
        "Id": str(5001 + i), "TxnDate": t["pay_date"].isoformat(), "TotalAmt": t["paid"],
        "CustomerRef": {"value": cust_id[t["customer"]], "name": t["customer"]},
        "Line": [{"Amount": t["paid"], "LinkedTxn": [{"TxnId": t["id"], "TxnType": "Invoice"}]}], "domain": "QBO",
    } for i, t in enumerate(t for t in qb.values() if t["paid"])]
    for name, entity, records in [("invoices", "Invoice", invoices), ("payments", "Payment", payments)]:
        resp = {"_note": NOTE, "QueryResponse": {entity: records, "startPosition": 1, "maxResults": len(records)},
                "time": f"{AS_OF.isoformat()}T23:00:00.000-07:00"}
        (SAMPLE / f"simulated_qbo_{name}.json").write_text(json.dumps(resp, indent=2))

    with open(SAMPLE / "simulated_planted_problems.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["invoice_number", "problem"])
        w.writerows(sorted(planted))
    print(f"  wrote SIMULATED sample data: {len(rows)} sheet rows, {len(invoices)} QBO invoices, "
          f"{len(payments)} QBO payments, {len(planted)} planted problems")


if __name__ == "__main__":
    main()
